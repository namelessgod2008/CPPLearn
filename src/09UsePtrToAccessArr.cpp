#include <iostream>

int main() {
    // ========================================================================
    // 一、(*ptr)++ ：修改指针所指的【值】，指针不动
    //     数组 arr 有两个独立的副本 arr / arr2，互不影响。
    //
    //     写法辨析（易混，务必记住）：
    //       *ptr++   ===  *(ptr++)   → 后缀++优先级高 → 移动指针，取出旧值
    //       (*ptr)++                → 括号强制先解引用 → 把"该位置的值"加1
    //       ++*ptr   ===  ++(*ptr)  → 值加1（前置版，这里用后置演示区别）
    //
    //     循环 i<5 而不是 i<6：指针越界是未定义行为！之前"两个5"就是
    //     i<6 让指针指到 arr[5]（数组末尾后）读到垃圾内存。修正为 i<5。
    // ========================================================================

    int arr[5] = {2, 4, 6, 8, 10};
    int arr2[5] = {2, 4, 6, 8, 10};
    int *ptr = &arr[0];

    for (int i = 0; i < 5; i++) {
        std::cout << *ptr << std::endl;   // 先打印当前值（2,3,4,5,6）
        (*ptr)++;                         // 再把"这个元素"加 1
    }
    // 第一段结束后：数组 arr 被改成 {3, 5, 7, 9, 11}
    // 打印的却是 2 3 4 5 6 —— 因为每次都是【先打印后自增】

    std::cout << '\n';

    // ========================================================================
    // 二、ptr++ ：只移动指针，【不改值】，遍历数组
    //     ptr2 = arr2  &&  ptr2 = &arr2[0]  等价（数组名会退化为首元素地址）
    //     这里输出的是数组【原始值】2,4,6,8,10，因为只动指针不碰元素。
    //     对比第一段：同样是 ++，作用于 [指针] 和 [所指的值] 效果天差地别。
    // ========================================================================

    int *ptr2 = arr2;   // 等价于 int *ptr2 = &arr2[0];

    for (int i = 0; i < 5; i++) {
        std::cout << *ptr2 << std::endl;   // 打印当前数组值（2,4,6,8,10）
        ptr2++;                           // 指针后移一位，数组内容不变
    }
    // 第二段结束后：arr2 仍是 {2, 4, 6, 8, 10}

    // ========================================================================
    // 核心结论：
    //   (*ptr)++  → 改【值】                      ptr++     → 改【指针】
    //   一个作用于所指的目标，一个作用于指针本身。
    //   而真正容易误写的是 *ptr++（=== *(ptr++)），它和 ptr++ 一样只是移动指针。
    // ========================================================================

    return 0;
}